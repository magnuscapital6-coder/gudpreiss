function translateText(text) {
  if (!text) return text;
  let result = text;
  for (const [fr, de] of frToDe) {
    result = result.split(fr).join(de);
  }
  return result;
}

// Now replace descriptions in current file
let descUpdated = 0;
let shortUpdated = 0;

for (const [id, data] of Object.entries(originalDescs)) {
  const translatedDesc = translateText(data.desc);
  const translatedShort = translateText(data.short);
  
  // Find this product in current file and update description
  const descPattern = new RegExp(`("id":\\s*"${id}"[\\s\\S]*?"description":\\s*")((?:[^"\\\\]|\\\\.)*?)(",\\s*\\n\\s*"short_description":\\s*")((?:[^"\\\\]|\\\\.)*?)(")`, 'm');
  
  const descMatch = current.match(descPattern);
  if (descMatch) {
    const escapedDesc = translatedDesc.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
    const escapedShort = translatedShort.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
    current = current.replace(descPattern, `$1${escapedDesc}$3${escapedShort}$5`);
    descUpdated++;
  }
}

fs.writeFileSync(filePath, current, 'utf8');
